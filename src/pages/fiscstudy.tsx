
import React, { useEffect, useState } from 'react';
import Head from "next/head";
import Container from "react-bootstrap/Container";
import Footer from "@/components/Footer";
import Header from "@/components/Header";

export default function Home() {
  const [plants, setPlants] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    async function fetchPlants() {
      try {
        const res = await fetch('/api/plantsTaxon');
        if (!res.ok) throw new Error('Failed to fetch plants_taxon');
        const data = await res.json();
        setPlants(data);
      } catch (err: any) {
        setError(err.message);
      } finally {
        setLoading(false);
      }
    }
    fetchPlants();
  }, []);

  async function handleSubmit(event: React.FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const form = event.currentTarget;
    const formData = new FormData(form);
    const comment = formData.get('comment');
    if (!comment) {
      alert('Please enter a comment.');
      return;
    }
    const res = await fetch('/api/submitComment', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ comment }),
    });
    if (res.ok) {
      alert('Comment submitted!');
      form.reset();
    } else {
      const data = await res.json();
      alert('Error: ' + (data.error || 'Unknown error'));
    }
  }

  return (
    <>
      <Head>
        <title>FISC</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      
      <Container as="section" className="text-bg-dark text-center projects-body">
        <Header state="projects" />

        <Container as="main" className="py-4 px-3 mx-auto">
          <h1>FISC</h1>
          <p className="fst-italic fs-sm yellow">
            Coming soon...
          </p>
        </Container>
      </Container>

      <Container as="section" className="text-bg-dark text-center projects-body">
        <h2>Plants Taxon Table</h2>
        {loading ? (
          <p>Loading...</p>
        ) : error ? (
          <p style={{ color: 'red' }}>{error}</p>
        ) : (
          <table border="1" cellPadding="5">
            <thead>
              <tr>
                {plants.length > 0 && Object.keys(plants[0]).map((key) => (
                  <th key={key}>{key}</th>
                ))}
              </tr>
            </thead>
            <tbody>
              {plants.map((row, idx) => (
                <tr key={idx}>
                  {Object.values(row).map((val, i) => (
                    <td key={i}>{String(val)}</td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        )}
      </Container>

      <Container as="section" className="section"> 
        <form onSubmit={handleSubmit}>
          <input type="text" placeholder="write a comment" name="comment" />
          <button type="submit">Submit</button>
        </form>
      </Container>
    </>
  );
}